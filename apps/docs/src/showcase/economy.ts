/** A value for every year: the anchors, and straight lines between them. */
const everyYear = (anchors: [number, number][], from: number, to: number) =>
  span(from, to).map((year) => {
    const next = anchors.findIndex(([y]) => y >= year)
    const [y1, v1] = anchors[next] as [number, number]
    const [y0, v0] = anchors[Math.max(0, next - 1)] as [number, number]
    return y1 === y0 ? v1 : Math.round((v0 + ((v1 - v0) * (year - y0)) / (y1 - y0)) * 10) / 10
  })

